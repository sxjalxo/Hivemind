"""Print the files a persona may overlay, as the pinned Cowrie image has them.

Run it with the container's own interpreter (the image is distroless, no shell):

    MSYS_NO_PATHCONV=1 docker exec -i hivemind-cowrie-1 /cowrie/cowrie-env/bin/python3 - \
        < infra/cowrie/personas/list_image_files.py > infra/cowrie/personas/image-files.txt

Re-run it whenever the Cowrie image digest in docker-compose.yml changes.

Why the list exists: Cowrie's honeyfs overlay attaches content only to nodes of
type T_FILE in its pickled filesystem. A file written anywhere else -- a path
the pickle lacks, or a symlink such as /etc/os-release -- is ignored with no
error and no log line, so a persona would look right on disk and change nothing.
The generator refuses any overlay path not listed here.
"""

import os
import pickle

from cowrie.shell import fs

PICKLE = "/cowrie/cowrie-git/src/cowrie/data/fs.pickle"
TXTCMDS = "/cowrie/cowrie-git/src/cowrie/data/txtcmds"

paths = []


def walk(node, path):
    for child in node[fs.A_CONTENTS]:
        here = f"{path}/{child[fs.A_NAME]}" if path else child[fs.A_NAME]
        if child[fs.A_TYPE] == fs.T_DIR:
            walk(child, here)
        elif child[fs.A_TYPE] == fs.T_FILE and (
            here.startswith(("etc/", "proc/")) or here == "usr/lib/os-release"
        ):
            paths.append("honeyfs/" + here)


with open(PICKLE, "rb") as handle:
    walk(pickle.load(handle), "")
for directory, _, files in os.walk(TXTCMDS):
    for name in files:
        paths.append("txtcmds/" + os.path.relpath(os.path.join(directory, name), TXTCMDS))

print("# Generated by list_image_files.py from the pinned Cowrie image -- do not edit.")
print("# Real files (T_FILE) a persona may overlay, and the packaged text commands.")
print("\n".join(sorted(paths)))
